export default function Tongs() {
  return (
    <svg
      className="po-tongs"
      viewBox={`0 0 ${REF.w} ${REF.h}`}
      aria-hidden="true"
      focusable="false"
    >
      <defs>
        {/*
          柄上的白斑。feTurbulence 的紅通道減掉一個偏置再放大，
          只有雜訊最亮的那一成多會留下來，剛好對上量到的 15%；
          留下來的顏色固定寫成 0.58（約 148），對上量到的 p95 = 149。
          color-interpolation-filters 一定要指定 sRGB，預設的 linearRGB
          會把亮度推歪。
        */}
        <filter
          id="po-tong-speck"
          x="0"
          y="0"
          width="100%"
          height="100%"
          colorInterpolationFilters="sRGB"
        >
          <feTurbulence
            type="fractalNoise"
            baseFrequency="1.1"
            numOctaves="2"
            seed="11"
            stitchTiles="stitch"
          />
          <feColorMatrix
            type="matrix"
            values="0 0 0 0 0.58 0 0 0 0 0.58 0 0 0 0 0.58 4 0 0 0 -2.6"
          />
        </filter>

        {TONGS.map(({ key, tong }) => (
          <clipPath key={key} id={`po-tong-clip-${key}`}>
            <path d={tong.body} />
          </clipPath>
        ))}
      </defs>

      {TONGS.map(({ key, tong }) => (
        <g key={key}>
          {/* 柄與描邊 */}
          <path d={tong.body} fill="var(--po-tong-ink)" />

          {/* 斑點只壓在柄上，所以裁進外形裡 */}
          <g clipPath={`url(#po-tong-clip-${key})`}>
            <rect
              x="0"
              y="0"
              width={REF.w}
              height={REF.h}
              filter="url(#po-tong-speck)"
              opacity="0.55"
            />
          </g>

          {/* 肉墊與夾片。畫在斑點上面，所以奶白是乾淨的 */}
          {tong.pads.map((d) => (
            <path key={d} d={d} fill={tong.cream} />
          ))}

          <path d={tong.seam} fill={tong.seamInk} />
        </g>
      ))}
    </svg>
  );
}
