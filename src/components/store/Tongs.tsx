const TONGS = [
  { key: "left", tong: LEFT },
  { key: "right", tong: RIGHT },
] as const;

/**
 * 夾子疊在鍋緣上面、碟子與標籤牌下面——參考圖的疊法就是這樣。
 * 整支純裝飾，所以 aria-hidden，也不吃滑鼠。
 */
export default function Tongs() {
  return (
    <svg
      className="po-tongs"
      viewBox={`0 0 ${REF.w} ${REF.h}`}
      aria-hidden="true"
      focusable="false"
    >
      <defs>
        {/*
          柄上的白斑。feTurbulence 的紅通道減掉一個偏置再放大，
          只有雜訊最亮的那 2% 會留下來，剛好對上量到的比例；
          留下來的顏色固定寫成 0.48（約 123），對上量到的 p99 = 123。
          color-interpolation-filters 一定要指定 sRGB，預設的 linearRGB
          會把亮度推歪。
        */}
        <filter
          id="po-tong-speck"
          x="0"
          y="0"
          width="100%"
          height="100%"
          colorInterpolationFilters="sRGB"
        >
          <feTurbulence
            type="fractalNoise"
            baseFrequency="1.1"
            numOctaves="2"
            seed="11"
            stitchTiles="stitch"
          />
          <feColorMatrix
            type="matrix"
            values="0 0 0 0 0.48 0 0 0 0 0.48 0 0 0 0 0.48 6 0 0 0 -4.4"
          />
        </filter>

        {TONGS.map(({ key, tong }) => (
          <clipPath key={key} id={`po-tong-clip-${key}`}>
            {tong.body.map((d) => (
              <path key={d} d={d} />
            ))}
          </clipPath>
        ))}
      </defs>

      {TONGS.map(({ key, tong }) => (
        <g key={key}>
          {/* 柄與描邊 */}
          {tong.body.map((d) => (
            <path key={d} d={d} fill={tong.ink} />
          ))}

          {/* 斑點只壓在柄上，所以裁進外形裡 */}
          <g clipPath={`url(#po-tong-clip-${key})`}>
            <rect
              x="0"
              y="0"
              width={REF.w}
              height={REF.h}
              filter="url(#po-tong-speck)"
              opacity="0.6"
            />
          </g>

          {/* 肉墊與夾片。畫在斑點上面，所以奶白是乾淨的 */}
          {tong.pads.map((d) => (
            <path key={d} d={d} fill={tong.cream} />
          ))}

          <path d={tong.seam} fill={tong.seamInk} />
        </g>
      ))}
    </svg>
  );
}
